import { test, expect } from '@playwright/test'
import { randomUUID } from 'node:crypto'
import { initializeApp } from '../functions/node_modules/firebase-admin/lib/esm/app/index.js'
import { getFirestore } from '../functions/node_modules/firebase-admin/lib/esm/firestore/index.js'
if (!process.env.FIRESTORE_EMULATOR_HOST) throw new Error('Execute node scripts/test-cards.mjs --browser')
test.beforeEach(async ({ context }) => { await context.route('**/*', route => { const host = new URL(route.request().url()).hostname; return ['127.0.0.1', 'localhost'].includes(host) ? route.continue() : route.abort() }) })
const db = getFirestore(initializeApp({ projectId: 'demo-tokka-cards' }))
async function fixture() {
  const email = `browser-${randomUUID()}@test.local`, password = 'Secret123!'
  const user = await (await fetch('http://127.0.0.1:19099/identitytoolkit.googleapis.com/v1/accounts:signUp?key=fake', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email, password, returnSecureToken: true }) })).json()
  await db.collection('cardsAdmins').doc(user.localId).set({ role: 'admin', active: true })
  return { email, password }
}
test('admin gera lote, baixa CSV/SVG e cliente ativa, edita e reabre perfil', async ({ page, browser }) => {
  const admin = await fixture()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/cartoes/admin')
  await page.getByLabel('E-mail', { exact: true }).fill(admin.email)
  await page.getByLabel('Senha', { exact: true }).fill(admin.password)
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Conexões começam aqui.' })).toBeVisible()
  await page.getByLabel('Quantidade de cartões').fill('3')
  await page.getByRole('button', { name: 'Gerar lote de cartões' }).click()
  await expect(page.getByText('3 cartões criados e salvos com sucesso.')).toBeVisible()
  const csv = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Planilha CSV' }).click()
  expect((await csv).suggestedFilename()).toMatch(/\.csv$/)
  const kit = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Kit de impressão e QRs' }).click()
  expect((await kit).suggestedFilename()).toMatch(/\.zip$/)
  await page.screenshot({ path: '.cards-test/admin-desktop.png', fullPage: true })
  const link = await page.getByRole('link', { name: 'Abrir QR' }).first().getAttribute('href')
  const client = await browser.newContext({ viewport: { width: 390, height: 844 } })
  const userPage = await client.newPage()
  await userPage.goto(`http://127.0.0.1:5174${link}`)
  await expect(userPage.getByText('Cartão encontrado e disponível para ativação.')).toBeVisible()
  await userPage.getByRole('button', { name: 'Criar conta', exact: true }).first().click()
  const email = `customer-${randomUUID()}@test.local`
  await userPage.getByLabel('E-mail', { exact: true }).fill(email)
  await userPage.getByLabel('Senha', { exact: true }).fill('Secret123!')
  await userPage.getByLabel('Confirme sua senha').fill('Secret123!')
  await userPage.getByRole('button', { name: 'Criar conta', exact: true }).last().click()
  await userPage.getByRole('button', { name: 'Ativar meu cartão', exact: true }).click()
  await expect(userPage.getByText('Cartão ativado com sucesso!')).toBeVisible()
  await userPage.getByRole('link', { name: 'Completar meu perfil' }).click()
  await userPage.getByLabel('Nome público').fill('Conexão de Teste')
  await userPage.getByLabel('Nome de usuário exclusivo').fill('conexao_teste')
  await userPage.getByLabel('Biografia').fill('Perfil salvo de verdade no Firestore.')
  await userPage.getByRole('button', { name: 'Salvar perfil', exact: true }).click()
  await expect(userPage.getByText('Seu perfil foi salvo.')).toBeVisible()
  await userPage.reload()
  await expect(userPage.getByLabel('Nome público')).toHaveValue('Conexão de Teste')
  await userPage.getByRole('button', { name: 'Sair', exact: true }).click()
  await userPage.getByLabel('E-mail', { exact: true }).fill(email)
  await userPage.getByLabel('Senha', { exact: true }).fill('Secret123!')
  await userPage.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(userPage.getByLabel('Nome público')).toHaveValue('Conexão de Teste')
  const visitor = await browser.newContext({ viewport: { width: 390, height: 844 } })
  const publicPage = await visitor.newPage()
  await publicPage.goto(`http://127.0.0.1:5174${link}`)
  await expect(publicPage).toHaveURL(/\/cartoes\/p\//)
  await expect(publicPage.getByRole('heading', { name: 'Conexão de Teste' })).toBeVisible()
  expect(await publicPage.locator('body').innerText()).not.toContain(email)
  await publicPage.screenshot({ path: '.cards-test/profile-mobile.png', fullPage: true })
  expect(await userPage.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
  await client.close(); await visitor.close()
})
test('entrada mobile e links antigos continuam no aplicativo original', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 })
  await page.goto('/cartoes/cadastro')
  await expect(page.getByLabel('Código de ativação')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.goto('/#cardapio-coco-bambu')
  await expect(page.locator('.tc-app')).toHaveCount(0)
  expect(page.url()).toContain('#cardapio-coco-bambu')
  await page.goto('/c/8Ks29#menu')
  await expect(page.locator('.tc-app')).toHaveCount(0)
})
